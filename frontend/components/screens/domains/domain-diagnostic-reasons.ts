export function domainDiagnosticReasonKey(reason: string) {
  switch (reason) {
    case "PLATFORM_OPERATOR_REQUIRED":
      return "platformOperatorRequired";
    case "DNS_NO_DATA":
      return "dnsNoData";
    case "ICMP_TIMEOUT":
      return "icmpTimeout";
    case "DNS_ANSWER":
      return "dnsAnswerHelp";
    case "PUBLIC_DELEGATION_MATCH":
      return "delegationMatch";
    case "INTERNAL_DNS_PROBE_NOT_CONFIGURED":
      return "internalDnsUnavailable";
    case "PUBLIC_DELEGATION_MISMATCH":
      return "mismatchHelp";
    case "DNS_NXDOMAIN":
      return "dnsNxdomain";
    case "DNS_TIMEOUT":
      return "dnsTimeout";
    case "DNS_LOOKUP_UNAVAILABLE":
      return "dnsLookupUnavailable";
    case "DNS_RESPONSE_INVALID":
      return "dnsResponseInvalid";
    case "DNS_RESPONSE_BOUND_EXCEEDED":
      return "dnsResponseBoundExceeded";
    case "DIAGNOSTIC_PROBE_UNAVAILABLE":
      return "probeUnavailable";
    case "PRIVATE_ZONE_PUBLIC_DELEGATION_NOT_APPLICABLE":
      return "privateZoneDelegation";
    case "PROVIDER_ACCESS_DENIED":
      return "providerAccessDenied";
    case "PROVIDER_ZONE_UNAVAILABLE":
      return "providerZoneUnavailable";
    case "PROVIDER_ZONE_NOT_BOUND":
      return "providerZoneNotBound";
    case "PROVIDER_CLUSTER_UNAVAILABLE":
      return "providerClusterUnavailable";
    case "TOOL_NOT_INSTALLED":
      return "toolNotInstalled";
    case "ICMP_REPLY":
      return "icmpReply";
    case "ICMP_UNCONFIRMED":
      return "icmpUnconfirmed";
    case "TLS_VERIFIED_HTTP_STATUS_OBSERVED":
      return "tlsVerifiedHelp";
    case "HTTPS_DEADLINE_EXCEEDED":
      return "httpsDeadline";
    case "PUBLIC_ADDRESS_REQUIRED":
      return "publicAddressRequired";
    case "CERTIFICATE_NOT_RECORDED":
      return "certificateNotRecorded";
    case "CERTIFICATE_TERMINATED_AT_EDGE":
      return "certificateEdgeTerminated";
    case "CERTIFICATE_CLUSTER_UNAVAILABLE":
      return "certificateClusterUnavailable";
    case "CERTIFICATE_UNAVAILABLE":
      return "certificateUnavailable";
    case "CERTIFICATE_ISSUED":
      return "certificateIssued";
    case "CERTIFICATE_PENDING_VALIDATION":
      return "certificatePending";
    case "CERTIFICATE_FAILED":
    case "CERTIFICATE_VALIDATION_TIMED_OUT":
    case "CERTIFICATE_EXPIRED":
    case "CERTIFICATE_REVOKED":
    case "CERTIFICATE_INACTIVE":
    case "NATIVE_CERTIFICATE_EXPIRED":
      return "certificateNotValid";
    case "NATIVE_CERTIFICATE_HOST_MISMATCH":
      return "certificateHostMismatch";
    case "NATIVE_ACCOUNT_CHANGED":
      return "certificateAccountChanged";
    default:
      return null;
  }
}
