# ABSBlobStoreDriver (Azure Blob Storage)
# ---------------------------------------------------------------------------


class ABSBlobStoreDriver:
    """BlobStoreDriver backed by Azure Blob Storage.

    ``account_url`` is the storage account URL (e.g.
    ``https://<account>.blob.core.windows.net``). ``container`` is the
    target container name. ``prefix`` is prepended to every key.
    """

    def __init__(
        self,
        *,
        account_url: str,
        container: str,
        prefix: str = "",
        credential: object | None = None,
        blob_service_client: object | None = None,
    ) -> None:
        self._container = container
        self._prefix = prefix.rstrip("/")
        if blob_service_client is not None:
            self._service = blob_service_client
        else:
            from azure.storage.blob import BlobServiceClient  # type: ignore[import-untyped]

            self._service = BlobServiceClient(
                account_url=account_url, credential=credential
            )

    def _full_key(self, key: str) -> str:
        if self._prefix:
            return f"{self._prefix}/{key.lstrip('/')}"
        return key

    def upload(
        self,
        key: str,
        data: bytes | Iterator[bytes],
        *,
        content_type: str = "application/octet-stream",
    ) -> None:
        payload = data if isinstance(data, bytes) else b"".join(data)
        client = self._service.get_blob_client(
            container=self._container, blob=self._full_key(key)
        )
        client.upload_blob(
            payload,
            overwrite=True,
            content_settings={"content_type": content_type},
        )

    def download(self, key: str) -> bytes:
        from azure.core.exceptions import ResourceNotFoundError  # type: ignore[import-untyped]

        client = self._service.get_blob_client(
            container=self._container, blob=self._full_key(key)
        )
        try:
            return client.download_blob().readall()
        except ResourceNotFoundError:
            raise BlobStoreNotFoundError(f"Blob not found: {key!r}")

    def presigned_url(self, key: str, *, expires_in: int = 900) -> str:
        import datetime

        from azure.core.exceptions import ResourceNotFoundError  # type: ignore[import-untyped]
        from azure.storage.blob import (  # type: ignore[import-untyped]
            BlobSasPermissions,
            generate_blob_sas,
        )

        full_key = self._full_key(key)
        client = self._service.get_blob_client(
            container=self._container, blob=full_key
        )
        try:
            client.get_blob_properties()
        except ResourceNotFoundError:
            raise BlobStoreNotFoundError(f"Blob not found: {key!r}")

        sas = generate_blob_sas(
            account_name=self._service.account_name,
            container_name=self._container,
            blob_name=full_key,
            account_key=self._service.credential.account_key,
            permission=BlobSasPermissions(read=True),
            expiry=datetime.datetime.utcnow() + datetime.timedelta(seconds=expires_in),
        )
        return f"{self._service.url}/{self._container}/{full_key}?{sas}"

    def delete(self, key: str) -> None:
        from azure.core.exceptions import ResourceNotFoundError  # type: ignore[import-untyped]

        client = self._service.get_blob_client(
            container=self._container, blob=self._full_key(key)
        )
        try:
            client.delete_blob()
        except ResourceNotFoundError:
            pass  # Idempotent

    def list_keys(self, prefix: str) -> list[BlobInfo]:
        full_prefix = self._full_key(prefix)
        results: list[BlobInfo] = []
        container_client = self._service.get_container_client(self._container)
        for blob in container_client.list_blobs(name_starts_with=full_prefix):
            raw_key = blob.name
            if self._prefix and raw_key.startswith(self._prefix + "/"):
                display_key = raw_key[len(self._prefix) + 1:]
            else:
                display_key = raw_key
            results.append(
                BlobInfo(
                    key=display_key,
                    size_bytes=blob.size or 0,
                    last_modified=blob.last_modified.isoformat() if blob.last_modified else "",
                )
            )
        return results


