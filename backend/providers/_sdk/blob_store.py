# GCSBlobStoreDriver (GCP)
# ---------------------------------------------------------------------------


class GCSBlobStoreDriver:
    """BlobStoreDriver backed by Google Cloud Storage.

    ``bucket`` is the GCS bucket name. ``prefix`` is prepended to every key.
    Presigned URLs use Blob.generate_signed_url v4.
    """

    def __init__(
        self,
        *,
        bucket: str,
        prefix: str = "",
        storage_client: object | None = None,
    ) -> None:
        self._bucket_name = bucket
        self._prefix = prefix.rstrip("/")
        if storage_client is not None:
            self._client = storage_client
        else:
            from google.cloud import storage  # type: ignore[import-untyped]

            self._client = storage.Client()
        self._bucket = self._client.bucket(self._bucket_name)

    def _full_key(self, key: str) -> str:
        if self._prefix:
            return f"{self._prefix}/{key.lstrip('/')}"
        return key

    def upload(
        self,
        key: str,
        data: bytes | Iterator[bytes],
        *,
        content_type: str = "application/octet-stream",
    ) -> None:
        import io

        blob = self._bucket.blob(self._full_key(key))
        payload = data if isinstance(data, bytes) else b"".join(data)
        blob.upload_from_file(io.BytesIO(payload), content_type=content_type)

    def download(self, key: str) -> bytes:
        from google.cloud.exceptions import NotFound  # type: ignore[import-untyped]

        blob = self._bucket.blob(self._full_key(key))
        try:
            return blob.download_as_bytes()
        except NotFound:
            raise BlobStoreNotFoundError(f"Blob not found: {key!r}")

    def presigned_url(self, key: str, *, expires_in: int = 900) -> str:
        import datetime

        from google.cloud.exceptions import NotFound  # type: ignore[import-untyped]

        blob = self._bucket.blob(self._full_key(key))
        if not blob.exists():
            raise BlobStoreNotFoundError(f"Blob not found: {key!r}")
        return blob.generate_signed_url(
            version="v4",
            expiration=datetime.timedelta(seconds=expires_in),
            method="GET",
        )

    def delete(self, key: str) -> None:
        from google.cloud.exceptions import NotFound  # type: ignore[import-untyped]

        blob = self._bucket.blob(self._full_key(key))
        try:
            blob.delete()
        except NotFound:
            pass  # Idempotent

    def list_keys(self, prefix: str) -> list[BlobInfo]:
        full_prefix = self._full_key(prefix)
        results: list[BlobInfo] = []
        for blob in self._client.list_blobs(self._bucket_name, prefix=full_prefix):
            raw_key = blob.name
            if self._prefix and raw_key.startswith(self._prefix + "/"):
                display_key = raw_key[len(self._prefix) + 1:]
            else:
                display_key = raw_key
            results.append(
                BlobInfo(
                    key=display_key,
                    size_bytes=blob.size or 0,
                    last_modified=blob.updated.isoformat() if blob.updated else "",
                )
            )
        return results


