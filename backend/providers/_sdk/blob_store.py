class MinioBlobStoreDriver:
    """BlobStoreDriver backed by MinIO (S3-compatible).

    MinIO exposes an S3-compatible API, so this driver delegates to
    S3BlobStoreDriver with the MinIO endpoint configured. ``endpoint_url``
    is the MinIO server URL (e.g. ``http://minio.minio-system.svc:9000``).
    ``access_key`` / ``secret_key`` are the MinIO credentials.
    """

    def __init__(
        self,
        *,
        endpoint_url: str,
        bucket: str,
        prefix: str = "",
        access_key: str,
        secret_key: str,
        region: str = "us-east-1",
    ) -> None:
        import boto3

        s3_client = boto3.client(
            "s3",
            endpoint_url=endpoint_url,
            aws_access_key_id=access_key,
            aws_secret_access_key=secret_key,
            region_name=region,
        )
        self._inner = S3BlobStoreDriver(
            bucket=bucket,
            region=region,
            prefix=prefix,
            s3_client=s3_client,
        )

    def upload(
        self,
        key: str,
        data: bytes | Iterator[bytes],
        *,
        content_type: str = "application/octet-stream",
    ) -> None:
        self._inner.upload(key, data, content_type=content_type)

    def download(self, key: str) -> bytes:
        return self._inner.download(key)

    def presigned_url(self, key: str, *, expires_in: int = 900) -> str:
        return self._inner.presigned_url(key, expires_in=expires_in)

    def delete(self, key: str) -> None:
        self._inner.delete(key)

    def list_keys(self, prefix: str) -> list[BlobInfo]:
        return self._inner.list_keys(prefix)


# ---------------------------------------------------------------------------
# Canonical path builder
# ---------------------------------------------------------------------------


def artifact_blob_key(
    *,
    env: str,
    org_id: str,
    pipeline_id: str,
    run_number: int,
    job_id: str,
    artifact_name: str,
) -> str:
    """Return the canonical blob key for a pipeline artifact.

    Layout:
        astrolift/{env}/{org_id}/pipelines/{pipeline_id}/runs/{run_number}/{job_id}/{artifact_name}

    All path components are URL-safe by convention; callers must validate
    ``artifact_name`` before passing it here.
    """
    return (
        f"astrolift/{env}/{org_id}/pipelines/{pipeline_id}"
        f"/runs/{run_number}/{job_id}/{artifact_name}"
    )


def run_blob_prefix(
    *,
    env: str,
    org_id: str,
    pipeline_id: str,
    run_number: int,
) -> str:
    """Return the blob key prefix for all artifacts in a pipeline run.

    Used to list or delete all artifacts for a given run.
    """
    return (
        f"astrolift/{env}/{org_id}/pipelines/{pipeline_id}/runs/{run_number}/"
    )


# ---------------------------------------------------------------------------
# Factory helper — used by artifact_store.py
# ---------------------------------------------------------------------------


def get_blob_driver(org: object) -> "BlobStoreDriver | None":
    """Return the configured BlobStoreDriver for the org's install, or None.

    Resolution order:
    1. Try the cluster's provider plugin blob_store driver via the plugin
       registry (production path for cloud installs).
    2. Fall back to LocalFsBlobStoreDriver when PIPELINE_ARTIFACT_LOCAL_PATH
       is set (dev / CI path).
    3. Return None — caller raises BlobStoreNotConfiguredError.

    ``org`` is the Django Organization model instance; this module avoids a
    direct import of that model so the providers tree stays import-isolated
    from the Django ORM.
    """
    local_path = os.environ.get("PIPELINE_ARTIFACT_LOCAL_PATH", "")
    if local_path:
        return LocalFsBlobStoreDriver(base_path=local_path)
    return None
